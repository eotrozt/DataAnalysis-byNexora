'use strict';
/* A self-contained worker lets the downloaded app run from file://.
   Embed only trusted application/dependency sources, never user data. */
const fs=require('node:fs');
const path=require('node:path');
const app=path.join(__dirname,'../app');
const sources=['vendor/xlsx.full.min.js','engine.js','insights.js','processor.js','reports.js','analysis-worker.js'];
const bundle=sources.map(name=>{
 let source=fs.readFileSync(path.join(app,name),'utf8');
 if(name==='analysis-worker.js')source=source.replace(/importScripts\([^)]*\);/g,'');
 return `/* ${name} */\n${source}\n;`;
}).join('\n');
fs.writeFileSync(path.join(app,'worker-source.js'),`/* Generated by scripts/build-worker.js; included in distribution. */\nconst NexoraWorkerSource=${JSON.stringify(bundle)};\n`);
console.log('worker: bundle local gerado');
